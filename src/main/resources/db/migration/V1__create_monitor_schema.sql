CREATE TABLE monitors (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    endpoint VARCHAR(2048) NOT NULL,
    interval_seconds INTEGER NOT NULL
        CHECK (interval_seconds BETWEEN 30 AND 3600),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(16) NOT NULL
        CHECK (status IN ('UNKNOWN', 'UP', 'DOWN', 'BLOCKED')),
    last_checked_at TIMESTAMPTZ,
    last_http_status INTEGER
        CHECK (last_http_status IS NULL OR last_http_status BETWEEN 100 AND 599),
    last_response_time_ms BIGINT
        CHECK (last_response_time_ms IS NULL OR last_response_time_ms >= 0)
);

CREATE TABLE monitor_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id UUID NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    endpoint VARCHAR(2048) NOT NULL,
    status VARCHAR(16) NOT NULL
        CHECK (status IN ('UNKNOWN', 'UP', 'DOWN', 'BLOCKED')),
    http_status INTEGER
        CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    response_time_ms BIGINT NOT NULL
        CHECK (response_time_ms >= 0),
    checked_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_monitor_checks_monitor_checked_at
    ON monitor_checks(monitor_id, checked_at DESC);
